import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

export interface InitOptions {
  cwd?: string;
  force?: boolean;
}

export interface InitResult {
  rootDir: string;
  configPath: string;
  created: string[];
  skipped: string[];
}

const STARTER_FIXTURE_DIR = path.join("fixtures", "hello-world");
const STARTER_FILES = {
  ["harnesscheck.yaml"]: buildStarterConfig(toPosixPath(STARTER_FIXTURE_DIR)),
  [path.join(STARTER_FIXTURE_DIR, "TASK.md")]: [
    "# Example task",
    "",
    "Create a file named `result.txt` in this workspace.",
    "Write exactly one line:",
    "",
    "HarnessCheck example passed",
    "",
  ].join("\n"),
  [path.join(STARTER_FIXTURE_DIR, "fake-agent.mjs")]: [
    'import { readFile, writeFile } from "node:fs/promises";',
    "",
    "async function readPrompt() {",
    "  const chunks = [];",
    "  for await (const chunk of process.stdin) chunks.push(Buffer.from(chunk));",
    '  return Buffer.concat(chunks).toString("utf8").trim();',
    "}",
    "",
    "const prompt = await readPrompt();",
    'const task = await readFile("TASK.md", "utf8");',
    'const line = task.includes("HarnessCheck example passed")',
    '  ? "HarnessCheck example passed\\n"',
    "  : `Unexpected task contents. Prompt was: ${prompt}\\n`;",
    'await writeFile("result.txt", line, "utf8");',
    "",
  ].join("\n"),
  [path.join(STARTER_FIXTURE_DIR, "README.md")]: [
    "This fixture is copied into an isolated workspace for each HarnessCheck trial.",
    "",
    "The bundled fake agent reads `TASK.md` and writes `result.txt`.",
    "",
  ].join("\n"),
} as const;

function buildStarterConfig(fixturePath: string): string {
  return [
    "# Generated by `harnesscheck init`.",
    "version: 1",
    "name: starter-suite",
    "",
    "defaults:",
    "  trials: 1",
    "  timeoutMs: 300000",
    "  assertionTimeoutMs: 60000",
    "  concurrency: 1",
    "  keep: failures",
    "  redact: true",
    "  outputDir: .harnesscheck",
    "",
    "agents:",
    "  fake:",
    "    adapter: custom",
    "    command: node",
    "    args:",
    "      - ./fake-agent.mjs",
    "    stdin: true",
    "    description: Deterministic example agent copied with the fixture.",
    "",
    "cases:",
    "  - id: hello-world",
    "    description: Sanity-check the harness with a deterministic fake agent.",
    `    fixture: ${fixturePath}`,
    "    prompt: |",
    "      Read TASK.md and create result.txt in the workspace.",
    "    assertions:",
    "      - type: file_exists",
    "        path: result.txt",
    "      - type: file_contains",
    "        path: result.txt",
    "        value: HarnessCheck example passed",
    "",
  ].join("\n");
}

function toPosixPath(filePath: string): string {
  return filePath.split(path.sep).join(path.posix.sep);
}

async function writeStarterFile(
  filePath: string,
  contents: string,
  force: boolean,
): Promise<"created" | "skipped"> {
  try {
    if (!force) {
      await readFile(filePath, "utf8");
      return "skipped";
    }
  } catch {
    // Missing file is expected.
  }

  await mkdir(path.dirname(filePath), { recursive: true });
  await writeFile(filePath, contents, "utf8");
  return "created";
}

export async function initHarness(options: InitOptions = {}): Promise<InitResult> {
  const rootDir = path.resolve(options.cwd ?? process.cwd());
  const force = options.force ?? false;
  const created: string[] = [];
  const skipped: string[] = [];

  for (const [relativePath, contents] of Object.entries(STARTER_FILES)) {
    const absolutePath = path.join(rootDir, relativePath);
    const outcome = await writeStarterFile(absolutePath, contents, force);
    const displayPath = toPosixPath(relativePath);
    if (outcome === "created") {
      created.push(displayPath);
      continue;
    }
    skipped.push(displayPath);
  }

  return {
    rootDir,
    configPath: path.join(rootDir, "harnesscheck.yaml"),
    created,
    skipped,
  };
}
